export const BUILTIN_LOCATION: SanyLocation = {
  file: "--TLA+ BUILTINS--",
  beginLine: 0,
  beginColumn: 0,
  endLine: 0,
  endColumn: 0,
};

export const createLevelFields = (id: number): LevelFields => ({
  id,
  levelChecked: 0,
  level: 0,
  levelParams: new Set(),
  allParams: new Set(),
  nonLeibnizParams: new Set(),
  unappliedParams: NO_UNAPPLIED_PARAMS,
  argLevelParams: new Map(),
  levelCorrect: true,
  levelConstraints: new Map(),
  argLevelConstraints: new Map(),
});

// SANY's order: OpDefNode's constructor numbers each builtin, then its phony parameters.
export const createBuiltins = (getId: () => number) =>
  BUILTIN_OPERATORS.map((operator): OpDefNode => {
    const id = getId();
    const params =
      operator[1] < 0
        ? undefined
        : Array.from({ length: operator[1] }, (_value, index): FormalParamNode => ({
            ...createLevelFields(getId()),
            kind: "FormalParam",
            name: `Formal_${index}`,
            arity: 0,
            location: undefined,
          }));
    const isLevelSet = operator[3] !== undefined && operator[4] !== undefined;
    const isLeibnizArg = operator[4]?.map((weight) => weight > 0);
    return {
      ...createLevelFields(id),
      levelChecked: isLevelSet ? 99 : 0,
      level: operator[2],
      kind: "OpDef",
      defKind: "BuiltIn",
      name: operator[0],
      arity: operator[1],
      params,
      body: undefined,
      isLocal: false,
      location: BUILTIN_LOCATION,
      module: undefined,
      source: undefined,
      preComments: [],
      isDefined: true,
      inRecursive: false,
      inRecursiveSection: false,
      recursiveSection: -1,
      letInLevel: 0,
      weights: operator[1] < 0 ? (operator[4] ?? []).slice(0, 1) : (operator[4] ?? []),
      isLeibnizArg: isLevelSet ? isLeibnizArg : undefined,
      isLeibniz: isLeibnizArg?.every(Boolean) ?? true,
      opLevelCond: undefined,
      maxLevels: operator[1] < 0 ? (operator[3] ?? []).slice(0, 1) : (operator[3] ?? []),
      minMaxLevel: undefined,
      labels: new Map(),
      step: undefined,
    };
  });
