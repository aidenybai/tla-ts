const BUILTIN_LOCATION: SanyLocation = {
  file: "--TLA+ BUILTINS--",
  beginLine: 0,
  beginColumn: 0,
  endLine: 0,
  endColumn: 0,
};

export const createLevelFields = (id: number): LevelFields => ({
  id,
  levelChecked: 0,
  level: 0,
  levelParams: new Set(),
  allParams: new Set(),
  nonLeibnizParams: new Set(),
  argLevelParams: new Map(),
});

// The builtin operators in the order SANY adds them to its global context.
export const createBuiltins = (getId: () => number) =>
  BUILTIN_OPERATORS.map(([name, arity, level, maxLevels, weights]): OpDefNode => {
    const params =
      arity < 0
        ? undefined
        : Array.from({ length: arity }, (_, index): FormalParamNode => ({
            ...createLevelFields(getId()),
            kind: "FormalParam",
            name: `Formal_${index}`,
            arity: 0,
            location: undefined,
          }));
    const isLevelSet = maxLevels !== undefined && weights !== undefined;
    const isLeibnizArg = weights?.map((weight) => weight > 0);
    return {
      ...createLevelFields(getId()),
      levelChecked: isLevelSet ? 99 : 0,
      level,
      kind: "OpDef",
      defKind: "BuiltIn",
      name,
      arity,
      params,
      body: undefined,
      isLocal: false,
      location: BUILTIN_LOCATION,
      module: undefined,
      source: undefined,
      preComments: [],
      isDefined: true,
      inRecursive: false,
      inRecursiveSection: false,
      recursiveSection: -1,
      letInLevel: 0,
      weights: arity < 0 ? (weights ?? []).slice(0, 1) : (weights ?? []),
      isLeibnizArg: isLevelSet ? isLeibnizArg : undefined,
      isLeibniz: isLeibnizArg?.every(Boolean) ?? true,
      opLevelCond: undefined,
    };
  });
