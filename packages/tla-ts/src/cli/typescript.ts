import { fileSystem } from "../file-system";
import { basename, dirname, join } from "node:path";
import { TlaTypeScriptError } from "../errors";

export const writeTypeScriptSpec = async (path: string) => {
  const compiled = (await import("../typescript/compile")).compile(
    fileSystem.readFileSync(path, "utf8"),
    path,
  );
  const header = `\\* Generated by tla-ts from ${basename(path)}. Edit ${basename(path)} instead.`;
  const specPath = join(dirname(path), `${compiled.name}.tla`);
  const configPath = join(dirname(path), `${compiled.name}.cfg`);
  for (const outputPath of [specPath, configPath]) {
    if (
      fileSystem.existsSync(outputPath) &&
      !fileSystem.readFileSync(outputPath, "utf8").startsWith(header)
    ) {
      throw new TlaTypeScriptError(
        `${outputPath} already exists, and tla-ts didn't generate it from ${path}`,
      );
    }
  }
  fileSystem.writeFileSync(specPath, `${header}\n${compiled.source}\n`);
  fileSystem.writeFileSync(configPath, `${header}\n${compiled.config}\n`);
  return specPath;
};
