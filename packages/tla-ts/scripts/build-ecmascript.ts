// Builds ecmascript/ESCore.tla from the parts in ecmascript/parts, in file order. TLA+ defines an
// operator before its use, so the module declares every operator that takes arguments RECURSIVE,
// which lets the parts call each other in any order. It also builds ecmascript/ESNames.tla, which
// maps each N("...") and SV("...") string the parts use to its UTF-16 code units.
// A part adds a family of built-ins with three definitions, so it needn't edit another part:
//   <Family>Builtin(s, f, m, this, args, nt)  runs the built-in with id <<"<Family>", m>>
//   <Family>Intrinsics                        the intrinsic objects it allocates
//   <Family>Properties                        the properties it gives the intrinsics
// The build joins them into CallBuiltin, Intrinsics, and RealmProperties.
// Usage: bun scripts/run.ts build-ecmascript

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseConfig } from "../src/config";
import { createEnvironment } from "../src/environment";

const ECMASCRIPT_DIRECTORY = join(import.meta.dirname, "../ecmascript");
const PARTS_DIRECTORY = join(ECMASCRIPT_DIRECTORY, "parts");

const parts = readdirSync(PARTS_DIRECTORY)
  .filter((name) => name.endsWith(".tla"))
  .toSorted()
  .map((name) => ({ name, text: readFileSync(join(PARTS_DIRECTORY, name), "utf8") }));

// An operator definition starts a line with its name and parameters, as in `Get(o, key, s) ==`.
const getOperators = (text: string) =>
  [...text.matchAll(/^([A-Z][A-Za-z0-9_]*)\((.*)\)\s*==/gm)].map((match) => ({
    name: match[1],
    parameters: match[2].split(",").map((parameter) => parameter.trim()),
  }));

const partText = parts.map((part) => part.text).join("\n");
const getFamilies = (pattern: RegExp) => [...partText.matchAll(pattern)].map((match) => match[1]);
const builtinFamilies = getFamilies(/^([A-Z][A-Za-z0-9]*)Builtin\(s, f, m, this, args, nt\) ==/gm);
const joinedDefinitions = [
  [
    "CallBuiltin(s, f, id, this, args, nt) ==",
    ...builtinFamilies.map(
      (family, index) =>
        `  ${index === 0 ? "CASE" : "  []"} id[1] = "${family}" -> ${family}Builtin(s, f, id[2], this, args, nt)`,
    ),
    '    [] OTHER -> Unsupported(s, N("Unsupported: built-in"))',
  ].join("\n"),
  `Intrinsics == ${getFamilies(/^([A-Z][A-Za-z0-9]*)Intrinsics ==/gm)
    .map((family) => `${family}Intrinsics`)
    .join(" \\o ")}`,
  `RealmProperties == ${getFamilies(/^([A-Z][A-Za-z0-9]*)Properties ==/gm)
    .map((family) => `${family}Properties`)
    .join(" \\o ")}`,
];

const texts = [...parts.map((part) => part.text), ...joinedDefinitions];
const operators = texts.flatMap(getOperators);
const duplicates = operators.filter(
  (operator, index) => operators.findIndex((other) => other.name === operator.name) !== index,
);
if (duplicates.length > 0) {
  throw new Error(`Defined twice: ${duplicates.map((operator) => operator.name).join(", ")}`);
}

const names = [
  ...new Set(
    texts.flatMap((text) =>
      [...text.matchAll(/\b(?:N|SV)\("((?:[^"\\]|\\.)*)"\)/g)].map((match) =>
        JSON.parse(`"${match[1]}"`),
      ),
    ),
  ),
].toSorted();

const getCodeUnits = (text: string) =>
  Array.from({ length: text.length }, (_, index) => text.charCodeAt(index));

writeFileSync(
  join(ECMASCRIPT_DIRECTORY, "ESNames.tla"),
  [
    "---- MODULE ESNames ----",
    "EXTENDS TLC",
    "\\* Generated by scripts/build-ecmascript.ts from the N(...) strings in parts. Don't edit.",
    "NameTable ==",
    ...names.map(
      (name, index) =>
        `  ${index === 0 ? "  " : "@@"} (${JSON.stringify(name)} :> <<${getCodeUnits(name).join(", ")}>>)`,
    ),
    "N(name) == NameTable[name]",
    "====",
    "",
  ].join("\n"),
);

// A definition is a line that starts with a name, with the comment lines above it. TLA+ needs a
// definition without parameters, or with an operator parameter, before its first use, so those
// come first.
const getDefinitions = (text: string) =>
  text
    .split(/\n(?=(?:\\\*.*\n)*[A-Z][A-Za-z0-9_]*(?:\(.*\))?\s*==)/)
    .map((definition) => definition.trimEnd())
    .filter((definition) => definition !== "");

const isEager = (definition: string) => {
  const header = definition.split("\n").find((line) => !line.startsWith("\\*")) ?? "";
  const match = /^[A-Z][A-Za-z0-9_]*(\((.*)\))?\s*==/.exec(header);
  return match !== null && (match[1] === undefined || match[2].includes("("));
};

const getName = (definition: string) =>
  /^([A-Z][A-Za-z0-9_]*)/m.exec(
    definition.split("\n").find((line) => !line.startsWith("\\*")) ?? "",
  )?.[1];

// A step `XThen(a, b, r) ==` takes the result r it waits on last. A suspended r passes on with a
// frame [step |-> "XThen", args |-> <<a, b>>], from which ResumeFrame runs the step again.
const STEP_PATTERN = /^([A-Z][A-Za-z0-9_]*Then)\(([^()]*)\)\s*==/;
const getStep = (definition: string) => {
  const match = STEP_PATTERN.exec(
    definition.split("\n").find((line) => !line.startsWith("\\*")) ?? "",
  );
  if (!match) return undefined;
  const parameters = match[2].split(",").map((parameter) => parameter.trim());
  return { name: match[1], args: parameters.slice(0, -1), result: parameters.at(-1) ?? "" };
};
const addSuspension = (definition: string) => {
  const step = getStep(definition);
  return step
    ? definition.replace(
        STEP_PATTERN,
        (header) =>
          `${header}\n  IF IsSuspended(${step.result}) THEN Pass(${step.result}, "${step.name}", <<${step.args.join(", ")}>>) ELSE`,
      )
    : definition;
};
const partDefinitions = parts.flatMap((part) => getDefinitions(part.text));
const steps = partDefinitions.flatMap((definition) => getStep(definition) ?? []);
const resumeFrame = [
  "ResumeFrame(frame, r) ==",
  ...steps.map(
    (step, index) =>
      `  ${index === 0 ? "CASE" : "  []"} frame.step = "${step.name}" -> ${step.name}(${[
        ...step.args.map((_, argIndex) => `frame.args[${argIndex + 1}]`),
        "r",
      ].join(", ")})`,
  ),
].join("\n");
operators.push({ name: "ResumeFrame", parameters: ["frame", "r"] });

const definitions = [...partDefinitions.map(addSuspension), ...joinedDefinitions, resumeFrame];

// Orders the eager definitions so each follows the eager definitions it names.
const eagerDefinitions = definitions.filter(isEager);
const eagerNames = new Set(eagerDefinitions.map(getName));
const orderedEagerDefinitions: string[] = [];
const visit = (definition: string, visiting: Set<string>) => {
  const name = getName(definition) ?? "";
  if (orderedEagerDefinitions.includes(definition) || visiting.has(name)) return;
  visiting.add(name);
  for (const match of definition.matchAll(/\b[A-Z][A-Za-z0-9_]*\b/g)) {
    const dependency = eagerDefinitions.find((other) => getName(other) === match[0]);
    if (match[0] !== name && eagerNames.has(match[0]) && dependency) visit(dependency, visiting);
  }
  orderedEagerDefinitions.push(definition);
};
for (const definition of eagerDefinitions) visit(definition, new Set());

writeFileSync(
  join(ECMASCRIPT_DIRECTORY, "ESCore.tla"),
  [
    "---- MODULE ESCore ----",
    "\\* Generated by scripts/build-ecmascript.ts from the files in parts. Don't edit.",
    "EXTENDS Integers, Sequences, FiniteSets, TLC, ESNumber, ESNames",
    "",
    "\\* Values the spec uses that aren't language values: a missing parse node, the empty",
    "\\* completion value, and a missing descriptor field. They are model values, so they compare",
    "\\* with any value.",
    "CONSTANTS None, Empty, Absent",
    "",
    // An operator that takes an operator argument is defined before its use instead.
    ...operators
      .filter((operator) => operator.parameters.every((parameter) => !parameter.includes("(")))
      .map(
        (operator) =>
          `RECURSIVE ${operator.name}(${operator.parameters.map(() => "_").join(", ")})`,
      ),
    "",
    ...orderedEagerDefinitions,
    "",
    ...definitions.filter((definition) => !isEager(definition)),
    "====",
    "",
  ].join("\n"),
);

// Loads the module as the test262 runner does, so a name no part defines fails the build.
createEnvironment(parseConfig("CONSTANTS None = None Empty = Empty Absent = Absent"), {
  source: "---- MODULE Check ----\nEXTENDS ESCore\n====",
  loadModule: (name) => {
    try {
      return readFileSync(join(ECMASCRIPT_DIRECTORY, `${name}.tla`), "utf8");
    } catch {
      return undefined;
    }
  },
  print: () => {},
  files: { readFile: undefined, writeFile: undefined },
});

console.log(`${parts.length} parts, ${operators.length} operators, ${names.length} names`);
