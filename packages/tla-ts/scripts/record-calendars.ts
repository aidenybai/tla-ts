// Records the Chinese and Dangi calendars, which Node computes astronomically, into
// src/typescript/calendars.ts, as the Node that runs it gives them: each year from 1800 through 2200,
// and each year outside them that test262's tests that name the calendar write, with the years
// either side, where the whole year is within Temporal's limits; and for each month code and day,
// the ISO reference date and the month code and day of the month-day that Temporal.PlainMonthDay
// constrains it to.
// Usage: bun scripts/run.ts record-calendars (with a Node that has Temporal)

import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { listTest262Files, TEST262_DIRECTORY } from "./corpora";

const CALENDARS = ["chinese", "dangi"];
const FIRST_YEAR = 1800;
const LAST_YEAR = 2200;

const getEpochDays = (date: Temporal.PlainDate) =>
  date.withCalendar("iso8601").since(new Temporal.PlainDate(1970, 1, 1)).days;

const getNamedYears = (calendar: string) =>
  listTest262Files()
    .filter((path) => /^(intl402|built-ins)\/Temporal\//.test(relative(TEST262_DIRECTORY, path)))
    .map((path) => readFileSync(path, "utf8"))
    .filter((text) => text.includes(calendar))
    .flatMap((text) =>
      [
        ...text.matchAll(/year: *(-?\d+)/g),
        ...text.matchAll(/Plain(?:Date|DateTime|YearMonth)\( *(-?\d+)/g),
        ...text.matchAll(/["'`]([+-]\d{6}|\d{4})-\d\d/g),
      ].map((match) => Number(match[1])),
    )
    .filter((year) => year < FIRST_YEAR || year > LAST_YEAR);

// A year's ISO start as epoch days, the ordinal of its leap month or 0, and its months of 30 days
// as bits from the first month's, or undefined where part of it is outside the limits.
const getYear = (calendar: string, year: number) => {
  try {
    const first = Temporal.PlainDate.from(
      { calendar, year, month: 1, day: 1 },
      { overflow: "reject" },
    );
    const months = Array.from({ length: first.monthsInYear }, (_, index) =>
      first.with({ month: index + 1, day: 1 }),
    );
    const last = months[months.length - 1];
    last.with({ day: last.daysInMonth }, { overflow: "reject" });
    const leap = months.findIndex((month) => month.monthCode.endsWith("L")) + 1;
    const long = months.reduce(
      (bits, month, index) => bits + (month.daysInMonth === 30 ? 2 ** index : 0),
      0,
    );
    return [year, getEpochDays(first), leap, long];
  } catch {
    return undefined;
  }
};

const getMonthDays = (calendar: string) =>
  Array.from({ length: 24 }, (_, index) => {
    const monthCode = `M${String((index >> 1) + 1).padStart(2, "0")}${index % 2 === 1 ? "L" : ""}`;
    return Array.from({ length: 30 }, (_, position) => {
      const day = position + 1;
      const result = Temporal.PlainMonthDay.from({ calendar, monthCode, day });
      const isKept = result.monthCode === monthCode && result.day === day;
      const isRejected = (() => {
        try {
          Temporal.PlainMonthDay.from({ calendar, monthCode, day }, { overflow: "reject" });
          return false;
        } catch {
          return true;
        }
      })();
      if (isKept === isRejected)
        throw new Error(`${calendar} ${monthCode} ${day} rejects a kept day`);
      const date = Temporal.PlainDate.from(result.toString({ calendarName: "never" }));
      return [
        getEpochDays(date),
        Number(result.monthCode.slice(1, 3)),
        result.monthCode.endsWith("L") ? 1 : 0,
        result.day,
      ];
    });
  });

const entries = CALENDARS.map((calendar) => {
  const named = new Set(getNamedYears(calendar).flatMap((year) => [year - 1, year, year + 1]));
  const years = [
    ...Array.from({ length: LAST_YEAR - FIRST_YEAR + 1 }, (_, index) => FIRST_YEAR + index),
    ...[...named]
      .filter((year) => year < FIRST_YEAR || year > LAST_YEAR)
      .sort((left, right) => left - right),
  ].flatMap((year) => {
    const entry = getYear(calendar, year);
    return entry === undefined ? [] : [entry];
  });
  return `  ${calendar}: {\n    years: [\n${years.map((year) => `      ${JSON.stringify(year)},`).join("\n")}\n    ],\n    monthDays: [\n${getMonthDays(
    calendar,
  )
    .map((row) => `      ${JSON.stringify(row)},`)
    .join("\n")}\n    ],\n  },`;
});

const header = `// Generated by scripts/record-calendars.ts from Node ${process.version}. Do not edit.
// The Chinese and Dangi calendars, which Node computes astronomically. years holds each recorded
// year as its number, the epoch days of its first day, the ordinal of its leap month or 0, and its
// months of 30 days as bits from the first month's. monthDays holds, for each month code from M01,
// M01L, M02 to M12L, and each day from 1 to 30, the ISO reference date as epoch days, and the month
// number, whether it is a leap month, and the day that a month-day of them is constrained to.

export interface CalendarTable {
  years: number[][];
  monthDays: number[][][];
}

export const CALENDAR_TABLES: Record<string, CalendarTable> = {
`;
writeFileSync(
  join(import.meta.dirname, "..", "src", "typescript", "calendars.ts"),
  `${header}${entries.join("\n")}\n};\n`,
);
