// The model Z3 5.3.2 prints for it under sat.restart=luby, in the order Z3 prints it.
const LUBY_MODEL = [
  35, -55, 43, 31, 54, -16, 13, 3, 20, 67, 28, 1, 37, -41, -15, -70, -46, 68, -61, -44, 33, 59, 10,
  42, 2, 23, 51, 49, 29, -11, 63, -38, -48, 52, 32, 60, 8, -26, 50, -57, -58, -24, 39, 45, 9, -21,
  36, 18, -25, -6, 12, -19, -7, -30, -69, -47, 66, 53, 56, -34, -27, 64, 14, 5, 17, -4, -62, 40,
  -22, -65,
];

const getName = (literal: number) => `x${Math.abs(literal) - 1}`;

describe("the SAT solver searches as Z3's does", () => {
  it("restarts on Z3's Luby sequence, so the model is the one Z3 finds", () => {
    expect(
      run([
        ...LUBY_MODEL.map((_, index) => `(declare-const x${index} Bool)`),
        ...LUBY_CLAUSES.map(
          (clause) =>
            `(assert (or ${clause.map((literal) => (literal < 0 ? `(not ${getName(literal)})` : getName(literal))).join(" ")}))`,
        ),
        "(check-sat-using (using-params sat :restart luby))",
        "(get-model)",
      ]).join("\n"),
    ).toBe(
      [
        "sat",
        "(",
        ...LUBY_MODEL.map(
          (literal) => `  (define-fun ${getName(literal)} () Bool\n    ${literal > 0})`,
        ),
        ")",
      ].join("\n"),
    );
  });
});

describe("the Horn engine reports what Z3 reports", () => {
  // Z3 prints a numerical symbol n as k!n (symbol.cpp), and rule_properties::check_uninterpreted_free
  // prints the function's symbol.
  it("names an uninterpreted function with a numerical symbol as Z3 does", () => {
    const manager = new AstManager(new ResourceLimit(Infinity));
    const variable = manager.mkVar(0, SORT_INT);
    const numbered = manager.mkApp(
      manager.mkFuncDecl(7, [SORT_INT], SORT_INT),
      [variable],
      SORT_INT,
    );
    const head = manager.mkApp(
      manager.mkFuncDecl("p", [SORT_INT], SORT_BOOL),
      [variable],
      SORT_BOOL,
    );
    const goal = new Goal(manager);
    goal.assert(
      mkForall(
        manager,
        [SORT_INT],
        ["x"],
        manager.mkApp(OP_IMPLIES, [manager.mkEq(numbered, variable), head], SORT_BOOL),
      ),
    );
    expect(() => runHorn(manager, new Map(), TACTIC_REWRITER_OPTIONS)(goal)).toThrow(
      new SmtTacticError("Uninterpreted 'k!7' in a rule"),
    );
  });
});
